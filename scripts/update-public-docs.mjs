import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const packageJson = JSON.parse(
  readFileSync(join(root, 'package.json'), 'utf8')
);
const gates = readFileSync(join(root, 'GATES.md'), 'utf8');
const gateMatches = [...gates.matchAll(/^- \[([ xX])\] G\d+:/gm)];
const metGates = gateMatches.filter(([ , state ]) => state.toLowerCase() === 'x').length;
const totalGates = gateMatches.length;
if (totalGates === 0) {
  throw new Error('GATES.md does not contain an acceptance ledger');
}

const description =
  'Evidence-driven harness factory for discovering, building, benchmarking, validating, and improving AI-agent architectures.';
const statusLines = [
  '# Fluid-Harness public status',
  '',
  'This file is generated by `scripts/update-public-docs.mjs` before each commit.',
  '',
  `- Package version: ${packageJson.version}`,
  `- Acceptance ledger: ${metGates}/${totalGates} gates marked met in [GATES.md](../GATES.md).`,
  '- Core boundary: bounded architecture discovery, evaluation, archival, research, and improvement; no automatic deployment or artificial-superintelligence claim.',
  '',
  'See [README.md](../README.md) for the public overview and [SCOPE_MATRIX.md](../SCOPE_MATRIX.md) for implemented versus future scope.',
  ''
];
const status = statusLines.join('\n');
mkdirSync(join(root, 'docs'), { recursive: true });
mkdirSync(join(root, '.github'), { recursive: true });
writeFileSync(join(root, 'docs', 'STATUS.md'), status);
writeFileSync(join(root, '.github', 'repository-description.txt'), `${description}\n`);

const startMarker = '<!-- FLUID_HARNESS_PUBLIC_STATUS:START -->';
const endMarker = '<!-- FLUID_HARNESS_PUBLIC_STATUS:END -->';
const readmeStatus = [
  startMarker,
  '## Public status',
  '',
  `- Package version: ${packageJson.version}`,
  `- Acceptance ledger: ${metGates}/${totalGates} gates marked met in [GATES.md](GATES.md).`,
  '- Scope: bounded architecture discovery, evaluation, archival, research, and improvement; no automatic deployment or artificial-superintelligence claim.',
  '- Generated detail: [docs/STATUS.md](docs/STATUS.md).',
  '',
  endMarker
].join('\n');
const readmePath = join(root, 'README.md');
let readme = readFileSync(readmePath, 'utf8');
const markerPattern = new RegExp(
  `${startMarker}[\\s\\S]*?${endMarker}`
);
if (markerPattern.test(readme)) {
  readme = readme.replace(markerPattern, readmeStatus);
} else {
  const titleEnd = readme.indexOf('\n');
  if (titleEnd === -1) {
    throw new Error('README.md must begin with a title');
  }
  readme = `${readme.slice(0, titleEnd + 1)}\n${readmeStatus}\n\n${readme.slice(titleEnd + 1)}`;
}
readme = readme.replace(
  /\[SCOPE_MATRIX\.md\]\(<[^>]*\/SCOPE_MATRIX\.md>\)/g,
  '[SCOPE_MATRIX.md](SCOPE_MATRIX.md)'
);
writeFileSync(readmePath, readme);

console.log(
  `FLUID_PUBLIC_DOCS_UPDATED version=${packageJson.version} `
  + `gates=${metGates}/${totalGates} descriptionLength=${description.length}`
);
